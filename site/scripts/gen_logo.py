"""Write src/components/LogoMark.astro from research/scripts/make_logo.py (the only source of the logo).

The mark is not hand-drawn: this script imports grid() and the CSS of make_logo.py and wraps them in an
Astro component. Run from site/:  python3 scripts/gen_logo.py   (also: npm run logo)."""
import os
import sys
sys.dont_write_bytecode = True  # never write into research/

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'research', 'scripts'))
import make_logo  # noqa: E402  (importing does not write any file: its writes are under __main__)

inner = make_logo.grid(6, 4 * 6 - 1)  # 6 × 6, 4 rows minus 1 square (make_logo.LOGO)
assert inner == make_logo.LOGO

component = f"""---
// GENERATED by site/scripts/gen_logo.py from research/scripts/make_logo.py. Do not edit by hand.
// Logo « Mille milliards » : grille 6 × 6, 4 lignes moins 1 case (fr/conception/03-identite-visuelle.md §2).
interface Props {{ size?: number }}
const {{ size = 24 }} = Astro.props;
---
<svg class="logo-mark" width={{size}} height={{size}} viewBox="0 0 32 32" aria-hidden="true" focusable="false"><Fragment set:html={{`{inner}`}} /></svg>
<style is:global>{make_logo.CSS}</style>
"""
out = os.path.join(HERE, '..', 'src', 'components', 'LogoMark.astro')
with open(out, 'w') as f:
    f.write(component)
print('ok', os.path.relpath(out, REPO))
